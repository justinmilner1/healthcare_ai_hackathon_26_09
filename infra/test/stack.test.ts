// Unit tests for the CDK stack (design §12.1 in spirit: the infrastructure is code too). Owner: ops.
//
// These assert the properties that would be expensive to learn from a deploy: that the bucket cannot be made
// public, that the database requires TLS and keeps seven days of backups, that the queue is drained once a
// minute, that every alarm reaches the topic, and — the one a reviewer should care about most — that no secret
// of any kind is in the synthesized template.
//
// `npx cdk synth` proves the stack is well formed. This proves it is the stack the design asked for.

import assert from "node:assert/strict";
import test from "node:test";
import * as cdk from "aws-cdk-lib";
import { Match, Template } from "aws-cdk-lib/assertions";
import { SECURE_PARAMETERS, SweetSpotStack } from "../lib/sweetspot-stack";
import { stageConfig } from "../lib/stage";

/** A staging stack with the repository's own cdk.json context, which is what `cdk synth` builds. */
function staging(context: Record<string, unknown> = {}): Template {
  const app = new cdk.App({
    context: {
      "sweetspot:staging": {
        region: "us-east-1",
        emailIdentity: "staging.sweetspot.example",
        emailFrom: "Sweet Spot <no-reply@staging.sweetspot.example>",
        repository: "https://github.com/justinmilner1/healthcare_ai_hackathon_26_09",
        branch: "main",
        ...context,
      },
    },
  });
  const stack = new SweetSpotStack(app, "SweetSpot-staging", { config: stageConfig(app, "staging"), env: { region: "us-east-1" } });
  return Template.fromStack(stack);
}

test("synthesizes with no context at all, which is what CI does", () => {
  const app = new cdk.App();
  const stack = new SweetSpotStack(app, "SweetSpot-staging", { config: stageConfig(app, "staging") });
  const template = Template.fromStack(stack);
  template.resourceCountIs("AWS::Amplify::App", 1);
  template.resourceCountIs("AWS::RDS::DBInstance", 1);
  // No SES identity without a sending domain: the stack is still complete, it just cannot send yet (§8).
  template.resourceCountIs("AWS::SES::EmailIdentity", 0);
});

test("the template carries no secret, in any shape", () => {
  const body = JSON.stringify(staging().toJSON());
  // The database password is generated by RDS into Secrets Manager and never passes through the template.
  assert.ok(!body.includes("sweetspot:sweetspot"), "the local development password is in the template");
  assert.match(body, /GenerateSecretString/);
  // SecureStrings are a deploy step (§10.6): CloudFormation has no SecureString, so none of these names may
  // appear as a parameter the stack writes. They appear once each in the output that lists what to create.
  for (const name of SECURE_PARAMETERS) {
    const parameters = staging().findResources("AWS::SSM::Parameter", { Properties: { Name: Match.stringLikeRegexp(`/${name}$`) } });
    assert.deepEqual(Object.keys(parameters), [], `${name} must not be written by the stack`);
  }
  // The GitHub token is a NoEcho template parameter, so it is not in the template either.
  staging().hasParameter("GitHubAccessToken", { NoEcho: true });
});

test("uploads: private, encrypted, TLS only, versioned (§3.3, §10.1)", () => {
  const template = staging();
  template.hasResourceProperties("AWS::S3::Bucket", {
    PublicAccessBlockConfiguration: { BlockPublicAcls: true, BlockPublicPolicy: true, IgnorePublicAcls: true, RestrictPublicBuckets: true },
    BucketEncryption: { ServerSideEncryptionConfiguration: [{ ServerSideEncryptionByDefault: { SSEAlgorithm: "AES256" } }] },
    VersioningConfiguration: { Status: "Enabled" },
  });
  // enforceSSL is a bucket policy, not a bucket property.
  template.hasResourceProperties("AWS::S3::BucketPolicy", {
    PolicyDocument: { Statement: Match.arrayWith([Match.objectLike({ Effect: "Deny", Condition: { Bool: { "aws:SecureTransport": "false" } } })]) },
  });
  template.hasResource("AWS::S3::Bucket", { DeletionPolicy: "Retain" });
});

test("database: Postgres 16, TLS required by the server, encrypted, seven days of backups (§3.2, §10.1, §11.4)", () => {
  const template = staging();
  template.hasResourceProperties("AWS::RDS::DBInstance", {
    Engine: "postgres",
    EngineVersion: Match.stringLikeRegexp("^16\\."),
    StorageEncrypted: true,
    BackupRetentionPeriod: 7,
    DBName: "sweetspot",
  });
  template.hasResourceProperties("AWS::RDS::DBParameterGroup", {
    Parameters: Match.objectLike({
      "rds.force_ssl": "1",
      // §10.3: a slow-query line may not carry the values the query was given, which are patient data.
      log_parameter_max_length: "0",
      log_parameter_max_length_on_error: "0",
    }),
  });
  // Nothing may reach 5432 until a deployment names a CIDR; see the comment on `database()`.
  template.hasResourceProperties("AWS::EC2::SecurityGroup", { SecurityGroupIngress: Match.absent() });
  template.hasResourceProperties("AWS::EC2::SecurityGroup", Match.objectLike({ GroupDescription: Match.stringLikeRegexp("dbAllowedCidrs") }));
});

test("a named CIDR is the only thing that opens the database", () => {
  const template = staging({ dbAllowedCidrs: ["203.0.113.0/24"] });
  template.hasResourceProperties("AWS::EC2::SecurityGroup", {
    SecurityGroupIngress: Match.arrayWith([Match.objectLike({ CidrIp: "203.0.113.0/24", FromPort: 5432, ToPort: 5432 })]),
  });
});

test("the job queue is drained once a minute by the schedule, not by the app (§3.4)", () => {
  const template = staging();
  template.hasResourceProperties("AWS::Scheduler::Schedule", {
    ScheduleExpression: "rate(1 minute)",
    State: "ENABLED",
    FlexibleTimeWindow: { Mode: "OFF" },
    Target: Match.objectLike({ RetryPolicy: { MaximumRetryAttempts: 0 } }),
  });
  // The app is told so too, or it would drain inline after every request as it does locally.
  template.hasResourceProperties("AWS::Amplify::Branch", {
    EnvironmentVariables: Match.arrayWith([{ Name: "JOBS_RUNNER", Value: "scheduled" }]),
  });
  template.hasResourceProperties("AWS::Lambda::Function", Match.objectLike({ FunctionName: "sweetspot-staging-jobs-tick", Handler: "index.handler" }));
});

test("the alarms §11.1 asks for exist, read the app's own log lines, and all reach the topic", () => {
  const template = staging();
  const patterns = Object.values(template.findResources("AWS::Logs::MetricFilter")).map((r) => r.Properties.FilterPattern);
  // §13.4: the three alarms that count a failure of *this practice's* work leave a demo practice's lines
  // out, and the label is what they leave out by (lib/log.ts, docs/LOGGING.md). The circuit is the
  // exception and counts everything: it is one per process, so a demo visit tripping it still means every
  // patient is reading scripted replies.
  assert.deepEqual(patterns.sort(), [
    '{ $.event = "job_failed" && $.demo NOT EXISTS }',
    '{ $.event = "llm_call_failed" && $.demo NOT EXISTS }',
    '{ $.event = "llm_circuit_opened" }',
    "{ $.status >= 500 && $.demo NOT EXISTS }",
  ]);
  const alarms = Object.values(template.findResources("AWS::CloudWatch::Alarm"));
  assert.equal(alarms.length, 6, "5xx, job failures, model failures, model degraded, the tick, and database storage");
  for (const alarm of alarms) {
    assert.ok(Array.isArray(alarm.Properties.AlarmActions) && alarm.Properties.AlarmActions.length === 1, `${alarm.Properties.AlarmName} has no action`);
  }
  template.resourceCountIs("AWS::SNS::Topic", 2); // alarms, and SES bounces and complaints (§8.1)
});

test("mail: the identity is verified, TLS is required, and bounces have somewhere to go (§8, §8.1, §10.1)", () => {
  const template = staging();
  template.hasResourceProperties("AWS::SES::EmailIdentity", { EmailIdentity: "staging.sweetspot.example" });
  template.hasResourceProperties("AWS::SES::ConfigurationSet", { DeliveryOptions: { TlsPolicy: "REQUIRE" } });
  template.hasResourceProperties("AWS::SES::ConfigurationSetEventDestination", {
    EventDestination: Match.objectLike({ MatchingEventTypes: Match.arrayWith(["bounce", "complaint"]) }),
  });
});

test("configuration comes from one SSM path, and the app may read it (§3.7, §10.6)", () => {
  const template = staging();
  const names = Object.values(template.findResources("AWS::SSM::Parameter")).map((r) => r.Properties.Name);
  for (const name of names) assert.ok(String(name).startsWith("/sweetspot/staging/"), `${name} is outside the stage's path`);
  assert.ok(names.some((n) => String(n).endsWith("/UPLOADS_BUCKET")));
  assert.ok(names.some((n) => String(n).endsWith("/APP_URL")));
  template.hasResourceProperties("AWS::IAM::Policy", {
    PolicyDocument: { Statement: Match.arrayWith([Match.objectLike({ Action: Match.arrayWith(["ssm:GetParametersByPath"]) })]) },
  });
});

test("the Dexcom plumbing is written by the stack, the credentials are not (§9.2, §4.10)", () => {
  const template = staging({ appUrl: "https://staging.sweetspot.health" });
  // The callback is this deployment's own URL. An operator who later puts the two credentials in SSM has a
  // whole Dexcom configuration without hand-typing anything — and `npm run config:check -- --production`,
  // which the Amplify build runs, passes before they do (lib/config.ts counts neither of these as intent).
  for (const type of ["AWS::Amplify::Branch", "AWS::SSM::Parameter"]) {
    const carries = JSON.stringify(template.findResources(type));
    assert.ok(carries.includes("https://staging.sweetspot.health/api/dexcom/callback"), `${type} has no DEXCOM_REDIRECT_URI`);
    assert.ok(carries.includes("DEXCOM_TOKEN_KMS_KEY_ID"), `${type} has no DEXCOM_TOKEN_KMS_KEY_ID`);
  }
  const body = JSON.stringify(template.toJSON());
  for (const name of ["DEXCOM_CLIENT_ID", "DEXCOM_CLIENT_SECRET", "DEXCOM_ENV"]) {
    assert.ok(!body.includes(`"${name}"`), `${name} is the operator's to set, not the stack's`);
  }
});

test("only this deployment's own origin may use a presigned PUT (§3.3)", () => {
  staging({ appUrl: "https://staging.sweetspot.health" }).hasResourceProperties("AWS::S3::Bucket", {
    CorsConfiguration: { CorsRules: [Match.objectLike({ AllowedOrigins: ["https://staging.sweetspot.health"] })] },
  });
  // With no domain of its own, the origin is the app's generated URL — a reference, never a wildcard.
  const generated = JSON.stringify(staging().findResources("AWS::S3::Bucket"));
  assert.ok(!generated.includes("*.amplifyapp.com"), "every Amplify site is not this deployment's origin");
  assert.ok(generated.includes("DefaultDomain"), "the CORS origin should resolve to this app's own domain");
});

test("the app itself holds no environment, so the secrets a human puts there survive a deploy (§10.6)", () => {
  const app = staging().findResources("AWS::Amplify::App");
  for (const resource of Object.values(app)) {
    assert.equal(resource.Properties.EnvironmentVariables, undefined, "CloudFormation must not own the app's variables");
  }
});

test("a stage with a domain of its own uses it for every link (§3.7)", () => {
  const template = staging({ appUrl: "https://staging.sweetspot.health" });
  template.hasResourceProperties("AWS::Amplify::Branch", {
    EnvironmentVariables: Match.arrayWith([{ Name: "APP_URL", Value: "https://staging.sweetspot.health" }]),
  });
});

test("production differs from staging only where the design says it does (§13.3)", () => {
  const app = new cdk.App({ context: { "sweetspot:production": { region: "us-east-1", branch: "release" } } });
  const template = Template.fromStack(new SweetSpotStack(app, "SweetSpot-production", { config: stageConfig(app, "production"), env: { region: "us-east-1" } }));
  template.hasResourceProperties("AWS::RDS::DBInstance", { MultiAZ: true, DeletionProtection: true, BackupRetentionPeriod: 7 });
  template.hasResource("AWS::RDS::DBInstance", { DeletionPolicy: "Retain" });
  template.hasResourceProperties("AWS::Amplify::Branch", { BranchName: "release", Stage: "PRODUCTION" });
});
